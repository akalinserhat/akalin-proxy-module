function interpolateTemplate(
  template: string,
  params?: Record<string, unknown>
): string {
  if (!params) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (_, key: string) => {
    const val = params[key];
    return val !== undefined && val !== null ? String(val) : '';
  });
}

export function createProxyTranslator(locale: SupportedProxyLocale = 'tr') {
  const dict = PROXY_MODULE_TRANSLATIONS[locale] || PROXY_MODULE_TRANSLATIONS.tr;
  return (key: string, params?: Record<string, unknown>): string => {
    const raw = dict[key] || PROXY_MODULE_TRANSLATIONS.tr[key] || key;
    return interpolateTemplate(raw, params);
  };
}

export function useProxyTranslation() {
  const { t: i18nT, i18n } = useTranslation();
  const lang: SupportedProxyLocale =
    i18n?.language && i18n.language.toLowerCase().startsWith('en') ? 'en' : 'tr';

  const t = useCallback(
    (key: string, params?: Record<string, unknown>): string => {
      const dict = PROXY_MODULE_TRANSLATIONS[lang] || PROXY_MODULE_TRANSLATIONS.tr;
      const fallback = dict[key] || PROXY_MODULE_TRANSLATIONS.tr[key] || key;
      if (typeof i18nT === 'function') {
        const translated = i18nT(key, { defaultValue: fallback, ...(params || {}) });
        if (translated && translated !== key) {
          return String(translated);
        }
      }
      return interpolateTemplate(fallback, params);
    },
    [i18nT, lang]
  );

  return { t, lang };
}
